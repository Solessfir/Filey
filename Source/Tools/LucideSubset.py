# Subsets the Lucide icon font to the icons in Source/Lib/Lucide/Icons.txt, remapped to consecutive codepoints from U+E000 so the app rasterizes them as one range, and writes Source/Lib/Lucide/Lucide.ttf, its LICENSE and Source/Meta/Icons.meta.h.
# Needs fontTools (pip install fonttools).
#
#   python Source/Tools/LucideSubset.py <extracted lucide-static npm package>

import json
import pathlib
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

FIRST_RUNE = 0xE000

source = pathlib.Path(sys.argv[1])
root = pathlib.Path(__file__).resolve().parents[1]
lib = root / "Lib" / "Lucide"

names = [line.strip() for line in (lib / "Icons.txt").read_text().splitlines() if line.strip() and not line.startswith("#")]
if len(set(names)) != len(names):
    sys.exit("Icons.txt lists an icon twice")
version = json.loads((source / "package.json").read_text())["version"]
codepoints = json.loads((source / "font" / "codepoints.json").read_text())
missing = [name for name in names if name not in codepoints]
if missing:
    sys.exit(f"Unknown icons: {', '.join(missing)}")

font = TTFont(source / "font" / "lucide.ttf")
cmap = font.getBestCmap()
glyphs = [cmap[codepoints[name]] for name in names]

options = subset.Options()
options.glyph_names = False
options.name_IDs = ["*"]
subsetter = subset.Subsetter(options)
subsetter.populate(glyphs=glyphs)
subsetter.subset(font)

# Center every glyph's ink in its advance, so that icons whose strokes lean to one side of Lucide's grid still center in their boxes. A subset glyph's stored bounds are stale until recalculated.
glyf = font["glyf"]
for name in font.getGlyphOrder():
    glyph = glyf[name]
    if glyph.numberOfContours <= 0:
        continue
    glyph.recalcBounds(glyf)
    advance, _ = font["hmtx"][name]
    shift = round((advance - (glyph.xMax - glyph.xMin)) / 2 - glyph.xMin)
    glyph.coordinates.translate((shift, 0))
    glyph.recalcBounds(glyf)
    font["hmtx"][name] = (advance, glyph.xMin)

for table in font["cmap"].tables:
    if table.isUnicode():
        table.cmap = {FIRST_RUNE + i: glyph for i, glyph in enumerate(glyphs)}
font.save(lib / "Lucide.ttf")
shutil.copyfile(source / "LICENSE", lib / "LICENSE")

def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))

lines = [
    f"// Generated by Tools/LucideSubset.py from Lib/Lucide/Icons.txt (lucide-static {version}). Do not edit.",
    "#pragma once",
    "",
    f"#define Icon_FirstRune 0x{FIRST_RUNE:X}",
    f"#define Icon_Count     {len(names)}",
    "",
]
width = max(len(pascal(name)) for name in names)
lines += [f"#define Icon_{pascal(name):<{width}} S(\"\\u{FIRST_RUNE + i:04X}\")" for i, name in enumerate(names)]
lines += [
    "",
    "global const u8 Icon_FontData[] = {",
    "#embed \"../Lib/Lucide/Lucide.ttf\"",
    "};",
    "",
]
(root / "Meta" / "Icons.meta.h").write_text("\n".join(lines), newline="\n")
print(f"{len(names)} icons from lucide-static {version}")
